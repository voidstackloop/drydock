// -f markdown / -f md: Rich Markdown report suitable for GitHub PR comments,
// GitLab MR notes, and release documentation summaries.
#include "internal.h"
#include "vulnerability.h"

#include <algorithm>
#include <map>
#include <ostream>

namespace lcreport {

void render_markdown(const Report &r, std::ostream &os) {
    size_t critical = 0, high = 0, medium = 0, low = 0;
    for (const Finding &f : r.findings) {
        const std::string s = severity_of(f);
        if (s == "critical")
            ++critical;
        else if (s == "high" || s == "error")
            ++high;
        else if (s == "medium" || s == "warning")
            ++medium;
        else
            ++low;
    }
    const size_t problems = critical + high + (r.min_severity != "error" ? medium : 0);
    const bool passed = problems == 0;

    os << "# \xF0\x9F\x9B\xA1\xEF\xB8\x8F leakcheck Security Report\n\n";
    os << "**Status:** " << (passed ? "\xE2\x9C\x85 **PASSED**" : "\xE2\x9D\x8C **ACTION REQUIRED**")
       << " | **Mode:** `" << r.mode << "` | **Total Findings:** " << r.findings.size()
       << " | **Failing Issues:** " << problems << "\n\n";

    os << "### Summary\n\n";
    os << "| Severity | Count | Threshold Status |\n";
    os << "|---|---|---|\n";
    os << "| \xF0\x9F\x9F\xA5 Critical | " << critical << " | " << (critical ? "FAIL" : "PASS") << " |\n";
    os << "| \xF0\x9F\x9F\xA7 High | " << high << " | " << (high ? "FAIL" : "PASS") << " |\n";
    os << "| \xF0\x9F\x9F\xA8 Medium | " << medium << " | " << (medium && r.min_severity != "error" ? "FAIL" : "PASS") << " |\n";
    os << "| \xF0\x9F\x9F\xA6 Low / Note | " << low << " | PASS |\n\n";

    if (r.findings.empty()) {
        os << "*No vulnerabilities, security weaknesses, or resource leaks detected.*\n";
        return;
    }

    os << "### Findings Detail\n\n";
    os << "| Severity | Rule | CWE | Location | Message |\n";
    os << "|---|---|---|---|---|\n";
    for (const Finding &f : r.findings) {
        const Frame *p = primary_frame(f);
        std::string loc = "—";
        if (p && !p->file.empty()) {
            loc = "`" + p->file;
            if (p->line)
                loc += ":" + std::to_string(p->line);
            loc += "`";
        }
        std::string cwe_str = "—";
        if (const lcvuln::VulnInfo *v = lcvuln::vuln_of(f.type.c_str())) {
            cwe_str = "[CWE-" + std::to_string(v->cwe) + "](https://cwe.mitre.org/data/definitions/" +
                      std::to_string(v->cwe) + ".html)";
        }
        std::string sev = severity_of(f);
        // Replace pipe characters in message to keep table syntax intact
        std::string msg = f.message;
        for (char &c : msg) {
            if (c == '|')
                c = '/';
            else if (c == '\n')
                c = ' ';
        }
        os << "| **" << sev << "** | `" << f.type << "` | " << cwe_str << " | "
           << loc << " | " << msg << " |\n";
    }

    os << "\n---\n*Report generated by leakcheck v" << kToolVersion << "*\n";
}

} // namespace lcreport
