#!/usr/bin/env python3
"""Write docs/rules/<id>.md from `leakcheck --rule-list -f json`.

    python3 tools/gen_rule_docs.py --build build [--check]

The text comes from the same table the scanner reports with, so a rule cannot
ship without a page. --check fails when a page is missing or out of date; CI
runs it on every change.
"""
import argparse
import json
import os
import sys

EXE = ".exe" if os.name == "nt" else ""
CWE_URL = "https://cwe.mitre.org/data/definitions/%d.html"


def page(rule):
    cwe = rule.get("cwe")
    lines = [
        "# %s (`%s`)" % (rule["name"], rule["id"]),
        "",
        "**CWE:** %s · **Severity:** %s · **Default run:** %s"
        % (("[CWE-%d](%s)" % (cwe, CWE_URL % cwe)) if cwe else "not mapped",
           rule.get("vulnerability_severity") or "n/a",
           "strict-only (`--strict`)" if rule.get("strict") else "reported"),
        "",
        rule["summary"] + ".",
        "",
        "## What it reports",
        "",
        rule["help"],
        "",
        "## When it is a false alarm",
        "",
        "A rule matches a shape of code, not a proof. This one is wrong when the",
        "program establishes the condition the rule cannot see: a check on another",
        "path, a wrapper that guarantees the invariant, or a value that is fixed by",
        "the time the code runs. Every finding from a rule that exceeded the 2%",
        "false-alarm budget is listed in `eval/PRECISION.md`.",
        "",
        "## Silencing one",
        "",
        "Add a rule to the suppression file, with a reason and an expiry date:",
        "",
        "```",
        "%s:<glob of the function or file> reason=\"why this is safe\" expires=YYYY-MM-DD",
        "```",
        "",
        "`leakcheck --audit-suppressions -s <file>` lists every silence and fails",
        "once one has expired, so a suppression is reviewed rather than forgotten.",
        "",
    ]
    return "\n".join(lines)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--build", default="build")
    ap.add_argument("--out", default="docs/rules")
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()

    leakcheck = os.path.join(args.build, "leakcheck" + EXE)
    if not os.path.exists(leakcheck):
        sys.exit("no %s: build first" % leakcheck)
    import subprocess
    p = subprocess.run([leakcheck, "--rule-list", "-f", "json"], capture_output=True, text=True)
    if p.returncode != 0:
        sys.exit(p.stderr)
    rules = json.loads(p.stdout)

    os.makedirs(args.out, exist_ok=True)
    stale = []
    for rule in rules:
        path = os.path.join(args.out, rule["id"] + ".md")
        text = page(rule)
        if args.check:
            try:
                if open(path, encoding="utf-8").read() != text:
                    stale.append(path)
            except FileNotFoundError:
                stale.append(path)
        else:
            with open(path, "w", encoding="utf-8") as f:
                f.write(text)

    index = ["# Rules", "", "%d rules. Generated by `tools/gen_rule_docs.py`." % len(rules), ""]
    for rule in rules:
        tag = " *(strict-only)*" if rule.get("strict") else ""
        index.append("* [%s](%s.md) — %s%s" % (rule["name"], rule["id"], rule["summary"], tag))
    index.append("")
    path = os.path.join(args.out, "index.md")
    if args.check:
        try:
            if open(path, encoding="utf-8").read() != "\n".join(index):
                stale.append(path)
        except FileNotFoundError:
            stale.append(path)
    else:
        with open(path, "w", encoding="utf-8") as f:
            f.write("\n".join(index))

    if stale:
        print("out of date: %d page(s), e.g. %s" % (len(stale), stale[0]), file=sys.stderr)
        return 1
    print("%d rule page(s) in %s" % (len(rules), args.out))
    return 0


if __name__ == "__main__":
    sys.exit(main())
