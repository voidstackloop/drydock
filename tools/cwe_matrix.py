#!/usr/bin/env python3
"""Write docs/CWE-COVERAGE.md from shared/include/vulnerability.h.

    python3 tools/cwe_matrix.py [--check]

The table of weaknesses comes from the source (one regex over kVulns), so a
finding type cannot be mapped in code and missing from the matrix. Coverage is
classified against the CWE Top 25: `supported` when the exact weakness is
mapped, `partial` when a closely related one is, `not covered` otherwise.
"""
import argparse
import json
import os
import re
import subprocess
import sys

HEADER = os.path.join("shared", "include", "vulnerability.h")
DOC = os.path.join("docs", "CWE-COVERAGE.md")

# CWE Top 25 (2024), with the weaknesses that are close enough to call partial.
TOP25 = [
    (79, "Improper Neutralization of Input During Web Page Generation ('Cross-site Scripting')", [79]),
    (787, "Out-of-bounds Write", [787, 120]),
    (89, "Improper Neutralization of Special Elements used in an SQL Command ('SQL Injection')", [89]),
    (352, "Cross-Site Request Forgery (CSRF)", [352]),
    (22, "Improper Limitation of a Pathname to a Restricted Directory ('Path Traversal')", [22]),
    (125, "Out-of-bounds Read", [125, 126]),
    (78, "Improper Neutralization of Special Elements used in an OS Command ('OS Command Injection')", [78, 77]),
    (416, "Use After Free", [416]),
    (862, "Missing Authorization", [862]),
    (434, "Unrestricted Upload of File with Dangerous Type", [434]),
    (94, "Improper Control of Generation of Code ('Code Injection')", [94]),
    (20, "Improper Input Validation", [20]),
    (77, "Improper Neutralization of Special Elements used in a Command ('Command Injection')", [77, 78]),
    (287, "Improper Authentication", [287]),
    (269, "Improper Privilege Management", [269]),
    (502, "Deserialization of Untrusted Data", [502]),
    (200, "Exposure of Sensitive Information to an Unauthorized Actor", [200]),
    (863, "Incorrect Authorization", [863]),
    (918, "Server-Side Request Forgery (SSRF)", [918]),
    (119, "Improper Restriction of Operations within the Bounds of a Memory Buffer", [119, 120]),
    (476, "NULL Pointer Dereference", [476]),
    (798, "Use of Hard-coded Credentials", [798]),
    (190, "Integer Overflow or Wraparound", [190, 680]),
    (400, "Uncontrolled Resource Consumption", [400, 401]),
    (306, "Missing Authentication for Critical Function", [306]),
]


def vulns(root):
    text = open(os.path.join(root, HEADER), encoding="utf-8").read()
    out = []
    for m in re.finditer(r"\{\s*(\d+),\s*(k\w+),\s*\"([^\"]+)\"", text):
        out.append({"cwe": int(m.group(1)), "type": m.group(2), "name": m.group(3)})
    return out


def rule_meta(root, build):
    """type -> (id, strict) from the built binary, when there is one."""
    exe = os.path.join(root, build, "leakcheck" + (".exe" if os.name == "nt" else ""))
    if not os.path.exists(exe):
        return {}
    p = subprocess.run([exe, "--rule-list", "-f", "json"], capture_output=True, text=True)
    if p.returncode != 0:
        return {}
    return {r["id"]: r for r in json.loads(p.stdout)}


def render(root, build):
    rows = vulns(root)
    by_cwe = {}
    for v in rows:
        by_cwe.setdefault(v["cwe"], []).append(v["type"])
    meta = rule_meta(root, build)

    out = [
        "# CWE Top 25 coverage",
        "",
        "Generated by `tools/cwe_matrix.py` from `shared/include/vulnerability.h`;",
        "CI runs `--check`, so the matrix cannot drift from the rules. Supported means",
        "a rule maps to that weakness; partial means a closely related weakness is",
        "detected and a reviewer still has to check the specific case; not covered",
        "means there is no rule for it.",
        "",
        "| CWE | Weakness | Coverage | Rules |",
        "|---|---|---|---|",
    ]
    for cwe, name, related in TOP25:
        exact = [t for c in related if c == cwe for t in by_cwe.get(c, [])]
        near = [t for c in related if c != cwe for t in by_cwe.get(c, [])]
        if exact:
            coverage = "supported"
        elif near:
            coverage = "partial"
        else:
            coverage = "not covered"
        rules = []
        for t in exact + near:
            r = meta.get(t, {})
            tag = " *(strict-only)*" if r.get("strict") else ""
            rules.append("`%s`%s" % (t, tag))
        link = "[CWE-%d](https://cwe.mitre.org/data/definitions/%d.html)" % (cwe, cwe)
        out.append("| %s | %s | %s | %s |" % (link, name, coverage, ", ".join(rules) or "—"))
    out += [
        "",
        "## Weaknesses outside the Top 25 that leakcheck does cover",
        "",
    ]
    top = {c for c, _, _ in TOP25}
    for cwe in sorted(by_cwe):
        if cwe in top:
            continue
        names = sorted({v["name"] for v in rows if v["cwe"] == cwe})
        out.append("* [CWE-%d](https://cwe.mitre.org/data/definitions/%d.html): %s (%s)"
                   % (cwe, cwe, names[0], ", ".join("`%s`" % t for t in sorted(by_cwe[cwe]))))
    out += [
        "",
        "## What is not covered",
        "",
        "Cross-site request forgery, unrestricted uploads, deserialization and missing",
        "authorization or authentication have no rule. They are application-framework",
        "concerns that a source-only checker cannot see: the framework decides whether",
        "a token is checked or a route is protected. Reporting them would be a guess,",
        "and a guess is what makes a gate ignored.",
        "",
    ]
    return "\n".join(out)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--root", default=".")
    ap.add_argument("--build", default="build")
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    text = render(args.root, args.build)
    path = os.path.join(args.root, DOC)
    if args.check:
        try:
            if open(path, encoding="utf-8").read() != text:
                print("%s is out of date; run tools/cwe_matrix.py" % DOC, file=sys.stderr)
                return 1
        except FileNotFoundError:
            print("%s is missing; run tools/cwe_matrix.py" % DOC, file=sys.stderr)
            return 1
    else:
        with open(path, "w", encoding="utf-8") as f:
            f.write(text)
        print("wrote %s" % DOC)
    return 0


if __name__ == "__main__":
    sys.exit(main())
